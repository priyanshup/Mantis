"""Read and write Mantis registers: one file per entry (stdlib only).

    python tools/entry.py next doc|gap|asm|cfl|dec|ast [N]   claim the next N IDs (safe across sessions)
    python tools/entry.py add  doc|gap|asm|cfl|dec|ast FILE [--still-new]   add entries from FILE ('-' = stdin), one file each;
                                                          a gap, conflict or assumption that looks settled already is refused
                                                          until checked (--still-new once it is)
    python tools/entry.py status ID "New status text"     replace an entry's Status line
    python tools/entry.py priority ID Level ["why"]       set Critical|High|Medium|Low (or none) on a gap, assumption or conflict
    python tools/entry.py note ID "Label" "Text"          append "- **Label (date):** Text" to an entry
    python tools/entry.py apply [--dry-run] FILE          many notes, statuses and priorities at once (format: entry.py apply --help-format)
    python tools/entry.py show ID [ID ...]                print entries
    python tools/entry.py check                           lint registers, digests and sources

Entries live in mantis/knowledge/registers/<folder>/<ID>.md (MANTIS-IMP-002, AD-010). Index
entries (documents/) are generated by build_map.py (MANTIS-IMP-013); `add doc` is not needed. Each file
holds one entry starting with "### <ID>". `add` refuses an ID that already has a file. Claims are
recorded in mantis/knowledge/id_claims.json under a lock file, so two sessions never receive the
same ID.
"""
import sys; sys.dont_write_bytecode = True  # keep __pycache__ out of OneDrive
import json, os, re, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
K = ROOT / "mantis" / "knowledge"
REG = K / "registers"
DIGESTS = ROOT / "mantis" / "02_digests"
SOURCES = ROOT / "mantis" / "01_sources"
CLAIMS = K / "id_claims.json"
LOCK = K / ".id_lock"

KINDS = {  # kind: (ID prefix, digits, folder)
    "doc": ("MANTIS-DOC-", 4, "documents"),
    "gap": ("MANTIS-GAP-", 3, "gaps"),
    "asm": ("MANTIS-ASM-", 3, "assumptions"),
    "cfl": ("MANTIS-CFL-", 3, "conflicts"),
    "dec": ("MANTIS-DEC-", 3, "decisions"),
    "ast": ("MANTIS-AST-", 3, "assets"),   # knowledge assets: diagrams and visuals (MANTIS-IMP-008)
}
STATUS_RE = re.compile(r"(?m)^- \*\*Status:\*\*.*(?:\n {2,}\S.*)*")


def folder(kind):
    return REG / KINDS[kind][2]


def kind_of(rid):
    for kind, (prefix, _, _) in KINDS.items():
        if rid.startswith(prefix):
            return kind
    sys.exit(f"Unknown ID: {rid}")


def path_of(rid):
    return folder(kind_of(rid)) / f"{rid}.md"


def blocks(text):
    """Yield (id, start, end) for each '### ID' entry in text."""
    heads = list(re.finditer(r"(?m)^### (\S+)", text))
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        yield m.group(1), m.start(), end


def ids_in(kind):
    prefix = KINDS[kind][0]
    found = [p.stem for p in folder(kind).glob(f"{prefix}*.md")]
    if kind == "doc":
        found += [p.stem for p in DIGESTS.glob("MANTIS-DOC-*.md")]
        found += [p.name for p in SOURCES.glob("MANTIS-DOC-*") if p.is_dir()]
    return found


def number(rid):
    return int(rid.rsplit("-", 1)[1])


def locked(fn):
    for _ in range(100):
        try:
            fd = os.open(LOCK, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
            break
        except FileExistsError:
            if time.time() - LOCK.stat().st_mtime > 60:  # stale lock from a crashed run
                LOCK.unlink(missing_ok=True)
            time.sleep(0.1)
    else:
        sys.exit("Could not get the ID lock; another session is busy. Try again.")
    try:
        return fn()
    finally:
        os.close(fd)
        LOCK.unlink(missing_ok=True)


def cmd_next(kind, n=1):
    prefix, digits, _ = KINDS[kind]

    def claim():
        claims = json.loads(CLAIMS.read_text(encoding="utf-8")) if CLAIMS.exists() else {}
        top = max([number(i) for i in ids_in(kind)] + [claims.get(kind, 0)])
        new = [f"{prefix}{top + i:0{digits}d}" for i in range(1, n + 1)]
        claims[kind] = top + n
        CLAIMS.write_text(json.dumps(claims, indent=1) + "\n", encoding="utf-8")
        return new

    print("\n".join(locked(claim)))


def cmd_add(kind, src, still_new=False):
    text = sys.stdin.read() if src == "-" else Path(src).read_text(encoding="utf-8")
    prefix = KINDS[kind][0]
    new = [(rid, text[s:e].strip() + "\n") for rid, s, e in blocks(text)]
    ids = [r for r, _ in new]
    if not new or any(not r.startswith(prefix) for r in ids):
        sys.exit(f"Entries must start with '### {prefix}...'. Found: {ids or 'none'}")
    if len(set(ids)) != len(ids):
        sys.exit(f"Duplicate IDs inside the input: {ids}")
    # Never ask the owner twice (MANTIS-IMP-088): a new question that looks like one already closed,
    # resolved or answered is refused until it has been checked. Read the entries listed; if one
    # settles the question, cite it instead. Only a question that is still new is added with --still-new.
    if kind in ("gap", "cfl", "asm") and not still_new:
        import answered
        if answered.check_entries(text):
            sys.exit("Nothing written. Read the entries above (python tools/entry.py show <ID>). If one already "
                     "settles it, do not raise it; otherwise re-run with --still-new.")

    def write():
        clash = [r for r in ids if path_of(r).exists()]
        if clash:
            sys.exit(f"Already in the register, nothing written: {clash}")
        folder(kind).mkdir(parents=True, exist_ok=True)
        for rid, body in new:
            path_of(rid).write_text(body, encoding="utf-8")

    locked(write)
    print(f"Added to registers/{KINDS[kind][2]}/: {', '.join(ids)}")


def read(rid):
    p = path_of(rid)
    if not p.exists():
        sys.exit(f"Not found: {rid}")
    return p, p.read_text(encoding="utf-8")


def cmd_status(rid, new_status):
    def change():
        p, text = read(rid)
        m = STATUS_RE.search(text)
        if not m:
            sys.exit(f"{rid} has no '- **Status:**' line.")
        print(f"{rid} was: {' '.join(m.group(0).split())}")
        p.write_text(text[:m.start()] + f"- **Status:** {new_status}" + text[m.end():], encoding="utf-8")
        print(f"{rid} now: {new_status}")

    locked(change)


PRIORITIES = ("Critical", "High", "Medium", "Low")
PRIORITY_RE = re.compile(r"(?m)^- \*\*Priority:\*\*.*\n?")


def cmd_priority(rid, level, why=""):
    """Set or replace an entry's Priority line (MANTIS-IMP-001); 'none' removes it."""
    level = level.capitalize()
    if level not in PRIORITIES + ("None",):
        sys.exit(f"Priority must be one of {', '.join(PRIORITIES)} or none.")
    if kind_of(rid) not in ("gap", "asm", "cfl"):
        sys.exit("Priority applies to gaps, assumptions and conflicts.")

    locked(lambda: set_priority(rid, level, why))


def set_priority(rid, level, why=""):
    """Write the Priority line; the caller holds the lock."""
    level = level.capitalize()
    p, text = read(rid)
    text = PRIORITY_RE.sub("", text)
    if level != "None":
        line = f"- **Priority:** {level}" + (f" ({' '.join(why.split())}, {time.strftime('%Y-%m-%d')})" if why else "") + "\n"
        m = re.search(r"(?m)^- \*\*Topic:\*\*.*\n(?: {2,}\S.*\n)*", text)
        at = m.end() if m else text.find("\n", text.find("### ")) + 1
        text = text[:at] + ("" if text[at - 1:at] == "\n" else "\n") + line + text[at:]
    p.write_text(text, encoding="utf-8")
    print(f"{rid}: priority {level.lower() if level == 'None' else level}")


def cmd_note(rid, label, text):
    def append():
        p, body = read(rid)
        line = f"- **{label} ({time.strftime('%Y-%m-%d')}):** {' '.join(text.split())}"
        p.write_text(body.rstrip("\n") + "\n" + line + "\n", encoding="utf-8")
        print(f"{rid}: added {label}")

    locked(append)


APPLY_HELP = """Batch file for `entry.py apply` (MANTIS-IMP-057): one block per entry, all checked before any is written.

## MANTIS-GAP-NNN   (the entry ID)
note Resolution: Source: Owner answer via the Open items page, 2026-10-10. The roles ...
  (indented lines continue the note above)
status: Closed (2026-10-10 by the owner: ...)
priority: High: optional reason
"""


def cmd_apply(src, dry=False):
    """Apply many notes, status changes and priorities in one call, under one lock."""
    text = sys.stdin.read() if src == "-" else Path(src).read_text(encoding="utf-8")
    plan, cur, problems = [], None, []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("<!--"):
            continue
        m = re.match(r"^##\s+(MANTIS-(?:GAP|ASM|CFL|DEC|AST)-\d+)\s*$", line)
        if m:
            cur = m.group(1)
            if not path_of(cur).exists():
                problems.append(f"line {n}: {cur} is not in the register")
            continue
        if line.startswith((" ", "\t")) and plan and plan[-1][1] == "note":
            plan[-1][3] += " " + line.strip()
            continue
        if cur is None:
            problems.append(f"line {n}: no '## <ID>' line before it")
            continue
        m = re.match(r"^note\s+([^:]{1,60}):\s*(.+)$", line)
        if m:
            plan.append([cur, "note", m.group(1).strip(), m.group(2).strip()])
            continue
        m = re.match(r"^status:\s*(.+)$", line)
        if m:
            plan.append([cur, "status", "", m.group(1).strip()])
            continue
        m = re.match(r"^priority:\s*(\w+)(?::\s*(.*))?$", line)
        if m and m.group(1).capitalize() in PRIORITIES + ("None",):
            plan.append([cur, "priority", m.group(1), (m.group(2) or "").strip()])
            continue
        problems.append(f"line {n}: not understood: {line[:80]}")
    if problems or not plan:
        sys.exit("Nothing written.\n" + "\n".join(problems or ["The file has no changes."]) + "\n\n" + APPLY_HELP)
    if dry:
        for rid, op, a, b in plan:
            print(f"{rid}: {op} {a + ': ' if a else ''}{b[:110]}")
        print(f"Dry run: {len(plan)} change(s) to {len({p[0] for p in plan})} entr(ies). Nothing written.")
        return

    def write_all():
        for rid, op, a, b in plan:
            p, body = read(rid)
            if op == "note":
                line = f"- **{a} ({time.strftime('%Y-%m-%d')}):** {' '.join(b.split())}"
                body = body.rstrip("\n") + "\n" + line + "\n"
            elif op == "status":
                m = STATUS_RE.search(body)
                if not m:
                    sys.exit(f"{rid} has no '- **Status:**' line; stopped after the changes before it.")
                body = body[:m.start()] + f"- **Status:** {b}" + body[m.end():]
            p.write_text(body, encoding="utf-8")
            if op == "priority":   # reuses the single-entry logic, already under this lock
                set_priority(rid, a, b)

    locked(write_all)
    print(f"Applied {len(plan)} change(s) to {len({p[0] for p in plan})} entr(ies): " + ", ".join(sorted({p[0] for p in plan})))


def cmd_show(ids):
    for rid in ids:
        p, text = read(rid)
        print(f"<!-- {p.relative_to(REG.parent).as_posix()} -->\n" + text.strip() + "\n")


def check():
    """Return a list of problems. Used by build_map.py as well."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import textcache
    problems = []
    for kind, (prefix, _, name) in KINDS.items():
        for p in sorted(folder(kind).glob("*.md")):
            if p.name == "README.md":
                continue
            heads = [rid for rid, _, _ in blocks(textcache.read(p))]
            if heads != [p.stem]:
                problems.append(f"registers/{name}/{p.name}: expected one entry '### {p.stem}', found {heads or 'none'}")
    digests = {p.stem for p in DIGESTS.glob("MANTIS-DOC-*.md")}
    indexed = {p.stem for p in folder("doc").glob("MANTIS-DOC-*.md")}
    sources = {p.name for p in SOURCES.glob("MANTIS-DOC-*") if p.is_dir()}
    problems += [f"{d}: digest has no index entry" for d in sorted(digests - indexed)]
    problems += [f"{d}: index entry has no digest" for d in sorted(indexed - digests)]
    problems += [f"{d}: digest has no source folder" for d in sorted(digests - sources)]
    problems += [f"{d}: source folder has no digest" for d in sorted(sources - digests)]
    known = {r for kind in ("gap", "asm", "cfl") for r in ids_in(kind)}
    for p in sorted(DIGESTS.glob("MANTIS-DOC-*.md")):
        head = textcache.read(p).split("\n---", 2)[0]
        for rid in sorted(set(re.findall(r"MANTIS-(?:GAP|ASM|CFL)-\d+", head)) - known):
            problems.append(f"{p.stem}: front matter cites {rid}, which is not in any register")
    return problems


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:2] == ["apply", "--help-format"]:
        sys.exit(APPLY_HELP)
    if not a or a[0] in ("-h", "--help"):
        sys.exit(__doc__)
    if a[0] == "next" and len(a) in (2, 3) and a[1] in KINDS:
        cmd_next(a[1], int(a[2]) if len(a) == 3 else 1)
    elif a[0] == "add" and len(a) in (3, 4) and a[1] in KINDS and (len(a) == 3 or a[3] == "--still-new"):
        cmd_add(a[1], a[2], still_new=len(a) == 4)
    elif a[0] == "status" and len(a) == 3:
        cmd_status(a[1], a[2])
    elif a[0] == "apply" and len(a) in (2, 3):
        cmd_apply(a[1] if a[1] != "--dry-run" else a[2], dry="--dry-run" in a)
    elif a[0] == "priority" and len(a) in (3, 4):
        cmd_priority(a[1], a[2], a[3] if len(a) == 4 else "")
    elif a[0] == "note" and len(a) == 4:
        cmd_note(a[1], a[2], a[3])
    elif a[0] == "show" and len(a) > 1:
        cmd_show(a[1:])
    elif a[0] == "check":
        found = check()
        print("\n".join(found) if found else "Registers OK.")
        sys.exit(1 if found else 0)
    else:
        sys.exit(__doc__)
