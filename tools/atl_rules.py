"""Rule checks on the mirrored Jira tickets (IMP-087, step 4). Code only: no AI, no network. Reads mantis/mirror/jira.

    python tools/atl.py rules            write mantis/mirror/reports/ticket-rules.md and print the counts

Checks, on tickets that are still open (not Done or Cancelled):
  - a Story or Improvement with no acceptance criteria in its description;
  - a Story with no parent (no Feature or Epic to roll up to);
  - a Feature that is Done or Cancelled while it still has open children.
They are prompts to look, never changes: a team may keep its criteria elsewhere, so each finding says what was missing and nothing is edited.
"""
import sys; sys.dont_write_bytecode = True  # keep __pycache__ out of OneDrive
import re
from pathlib import Path

CLOSED = {"done", "cancelled", "closed", "resolved"}
NEEDS_CRITERIA = {"Story", "Improvement"}
CRITERIA = re.compile(r"acceptance criteria|\bAC\b\s*[:\-]|definition of done|\bgiven\b.{0,120}\bwhen\b.{0,120}\bthen\b|\bshould be able to\b|\bmust\b.{0,60}\bwhen\b", re.I | re.S)


def is_open(item):
    return str(item.get("status", "")).strip().lower() not in CLOSED


def check(index, body_of):
    """[(key, rule, text)] for every finding. `body_of(key)` returns the ticket's text ('' when it is not mirrored)."""
    findings = []
    children = {}
    for key, it in index.items():
        if it.get("parent"):
            children.setdefault(it["parent"], []).append(key)
    for key, it in sorted(index.items()):
        t, summary = it.get("type", ""), it.get("summary", "")
        if is_open(it) and t in NEEDS_CRITERIA:
            body = body_of(key)
            if body and not CRITERIA.search(body):
                findings.append((key, "no-criteria", f"{t} '{summary}' has no acceptance criteria in its description"))
        if is_open(it) and t == "Story" and not it.get("parent"):
            findings.append((key, "no-parent", f"Story '{summary}' has no Feature or Epic above it"))
        if t == "Feature" and not is_open(it):
            kids = [k for k in children.get(key, []) if k in index and is_open(index[k])]
            if kids:
                findings.append((key, "closed-with-open-children", f"Feature '{summary}' is {it.get('status')} but {len(kids)} child ticket(s) are still open: {', '.join(sorted(kids)[:6])}"))
    return findings


def report(findings, total):
    titles = {"no-criteria": "No acceptance criteria", "no-parent": "Story with no parent", "closed-with-open-children": "Feature closed with open children"}
    out = ["# Ticket rule checks", "", f"Generated by `python tools/atl.py rules` from the Jira mirror ({total} tickets). Code checks only: each line is a prompt to look, nothing was changed.", ""]
    for rule, title in titles.items():
        rows = [(k, t) for k, r, t in findings if r == rule]
        out += [f"## {title} ({len(rows)})", ""] + ([f"- {k}: {t}" for k, t in rows] or ["- none"]) + [""]
    return "\n".join(out)


def run(mirror):
    import json
    mirror = Path(mirror)
    index = json.loads((mirror / "jira" / "index.json").read_text(encoding="utf-8"))

    def body_of(key):
        try:
            return (mirror / "jira" / "issues" / f"{key}.md").read_text(encoding="utf-8")
        except OSError:
            return ""

    findings = check(index, body_of)
    return findings, report(findings, len(index))
