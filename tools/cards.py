"""Cards: the reading layer for every subject (MANTIS-IMP-014). Stdlib only, deterministic.

A card is a Markdown file in mantis/knowledge/features/ (roadmap features and workstreams) or
mantis/knowledge/topics/ (any other subject). It has two parts:

1. A curated part, written by Claude or the owner: the summary and whatever sections help.
   Front matter `source_documents` lists the digests this curated part already covers.
2. A generated part, rewritten on every rebuild below the GENERATED marker: every linked
   source with a one-line summary (sources not yet covered by the curated part are marked
   new), open questions with live status, and the people and systems named in the sources.

A digest links to a card when its id is in `source_documents` or one of its topic tags is in
the card's `match_topics`. So a new digest reaches its cards with no manual step, and a card
says how many sources its summary has not caught up with yet.
"""
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
K = ROOT / "mantis" / "knowledge"
FOLDERS = {"features": K / "features", "topics": K / "topics"}
MARK = "<!-- GENERATED by tools/cards.py on every rebuild, from the digests and registers. Edit above this line only. -->"
ID_RE = re.compile(r"MANTIS-(?:DOC|GAP|ASM|CFL)-\d+")


def first_sentence(summary, limit=230):
    s = re.sub(r"\s+", " ", summary).strip()
    s = re.split(r"(?<=[.!?])\s(?=[A-Z\"(])", s)[0] if s else ""
    return s if len(s) <= limit else s[:limit - 1].rsplit(" ", 1)[0] + "…"


def load(front_matter):
    """Read every card. Returns a list of dicts with front matter, path and curated text."""
    cards = []
    for kind, folder in FOLDERS.items():
        for p in sorted(folder.glob("*.md")):
            if p.name == "README.md":
                continue
            text = p.read_text(encoding="utf-8")
            fm = front_matter(text)
            curated = text.split(MARK)[0].rstrip() + "\n"
            cards.append({"path": p, "folder": kind, "fm": fm, "slug": fm.get("feature", fm.get("topic", p.stem)),
                          "title": fm.get("title", p.stem), "type": fm.get("type", "feature" if kind == "features" else "topic"),
                          "curated": curated, "old": text})
    return cards


def link(cards, docs, summaries):
    """Attach linked, covered and new document lists to each card."""
    for c in cards:
        fm = c["fm"]
        covered = [d for d in fm.get("source_documents", []) if d in docs]
        match = set(fm.get("match_topics", []))
        exclude = set(fm.get("exclude_documents", []))
        auto = {d for d, f in docs.items() if match & set(f.get("topics", []))}
        linked = sorted((set(covered) | auto) - exclude, reverse=True)
        c.update(covered=covered, linked=linked, new=[d for d in linked if d not in covered])
    return cards


def block(c, docs, summaries, gaps, entities, is_open):
    rows = ["## Sources (auto)", "",
            f"{len(c['linked'])} source(s). The summary above covers {len(c['covered'])}"
            + (f"; {len(c['new'])} newer one(s) are marked new and not yet reflected in it." if c["new"] else "."), ""]
    if c["linked"]:
        rows += ["| Doc | Added | Title | In short |", "|---|---|---|---|"]
        for d in c["linked"]:
            f = docs[d]
            added = f.get("generated_on", "")[:10] + (" (new)" if d in c["new"] else "")
            title = f.get("original_title", "").replace("|", "/")
            rows.append(f"| {d} | {added} | {title} | {first_sentence(summaries.get(d, '')).replace('|', '/')} |")
    open_ids = set(c["fm"].get("gaps", [])) | {g for d in c["linked"] for r in docs[d].get("gaps_referenced", []) for g in ID_RE.findall(r)}
    open_rows = sorted((g for g in open_ids if g in gaps and is_open(gaps[g]["status"])), key=lambda g: -int(g.rsplit("-", 1)[1]))
    rows += ["", "## Open questions (auto)", ""]
    if open_rows:
        rows += ["| ID | Status | Question |", "|---|---|---|"]
        rows += [f"| {g} | {gaps[g]['status']} | {gaps[g]['topic'][:200].replace('|', '/')} |" for g in open_rows[:25]]
        if len(open_rows) > 25:
            rows.append(f"\n{len(open_rows) - 25} more in `map/registers.md`.")
    else:
        rows.append("None open.")
    named = Counter()
    for e in entities:
        if e["type"] in ("person", "system", "team", "organisation", "distributor"):
            n = len(set(e["docs"]) & set(c["linked"]))
            if n:
                named[(e["name"], e["type"])] = n
    if named:
        rows += ["", "## People and systems (auto)", "",
                 ", ".join(f"{n} ({t}, {k})" for (n, t), k in named.most_common(14)) + "."]
    return "\n".join(rows) + "\n"


def write(cards, docs, summaries, gaps, entities, is_open):
    """Rewrite each card's generated part. Returns the number of files changed."""
    changed = 0
    for c in cards:
        new = c["curated"].rstrip() + "\n\n" + MARK + "\n\n" + block(c, docs, summaries, gaps, entities, is_open)
        if new != c["old"]:
            c["path"].write_text(new, encoding="utf-8")
            changed += 1
    return changed


def uncovered_tags(cards, docs, minimum=3):
    """Topic tags carried by at least `minimum` digests that no card links: candidates for new cards."""
    linked = {d for c in cards for d in c["linked"]}
    count = Counter(t for d, f in docs.items() if d not in linked for t in f.get("topics", []))
    return [(t, n) for t, n in count.most_common() if n >= minimum]
