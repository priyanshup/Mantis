"""IMP-109: `context.py <subject>` answers "where do things stand on X" in a few hundred tokens: the card's lead and key facts, the open questions, the people and
systems, and pointers to the digests and their sections. The map files and the cards are made up here; nothing real is read."""
import sys; sys.dont_write_bytecode = True  # keep __pycache__ out of OneDrive
import json, tempfile, unittest
from pathlib import Path
from unittest import mock

import context

P = "MANTIS" + "-"   # built from parts so the test text holds no real-looking knowledge id
DOC = lambda n: f"{P}DOC-{n:04d}"
GAP = lambda n: f"{P}GAP-{n:03d}"

CARD = f"""---
feature: rollout
title: "Rollout tracking"
status: build
---

## In one paragraph

Rollout tracking is how the team follows the install across the distributors. It is in build and waits on the install check ({DOC(7)}). A second sentence that goes on for a while.

## Problem and outcome
- **Outcome wanted:** Every distributor installed by March ({DOC(7)}).
- **Next decision:** Whether to pause the install in week 50 ({DOC(9)}).

## Business rules agreed so far
- A rule ({DOC(7)}).

<!-- GENERATED by tools/cards.py on every rebuild, from the digests and registers. Edit above this line only. -->

## Sources (auto)

- {DOC(9)}: a source line
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class Case(unittest.TestCase):
    OPEN = []
    ENTITIES = []
    DOCS = [5, 7, 8, 9]

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        m = Path(self.tmp.name) / "mantis"
        self.m, self.map = m, m / "knowledge" / "map"
        write(m / "knowledge" / "features" / "rollout.md", CARD)
        feature = {"slug": "rollout", "title": "Rollout tracking", "type": "workstream", "status": "build", "priority": "P2", "jira": "CUD-1", "updated": "2026-11-12",
                   "card": "knowledge/features/rollout.md", "docs": [DOC(n) for n in self.DOCS], "kind": "feature", "epics": [], "stories": [], "page": ""}
        write(self.map / "features.json", json.dumps([feature]))
        write(self.map / "topics.json", json.dumps([{"slug": "pricing", "title": "Pricing and promotions", "card": "knowledge/topics/pricing.md", "docs": [DOC(5)], "kind": "topic"}]))
        write(self.map / "open-items.json", json.dumps(self.OPEN))
        write(self.map / "entities.json", json.dumps({"entities": self.ENTITIES, "candidates": [], "problems": []}))
        write(self.map / "titles.json", json.dumps({DOC(n): f"Source number {n}" for n in range(1, 30)}))
        for n in self.DOCS:
            write(m / "02_digests" / f"{DOC(n)}.md", f"---\ndocument_id: {DOC(n)}\n---\n\n## Summary\n\nDigest {n} says something short. And then more words.\n\n## Business Rules\n\n- x\n")
        for target, value in (("M", m), ("MAP", self.map)):
            p = mock.patch.object(context, target, value)
            p.start()
            self.addCleanup(p.stop)

    def ask(self, subject, **kw):
        return context.render(subject, **kw)


def item(i, status="Open", priority="", topic="a question", features=("rollout",)):
    return {"id": GAP(i), "kind": "gap", "status": status, "priority": priority, "topic": f"{topic} {i}", "features": list(features), "docs": [], "ask": None, "raised": "2026-11-01"}


def person(name, docs, slug="rollout", kind="person"):
    return {"id": name, "name": name, "type": kind, "aliases": [], "docs": [DOC(5)], "features": [{"slug": slug, "title": "Rollout tracking", "docs": docs, "kind": "feature"}],
            "neighbours": [], "relations": []}


class CardContext(Case):
    OPEN = [item(1, priority="Low"), item(2, priority="High"), item(3, status="Closed"), item(4, priority="Critical"), item(5, features=("pricing",))]
    ENTITIES = [person("Sam Lee", 6), person("Alex Roe", 9), person("Tag Tool", 4, kind="system"), person("Other Person", 3, slug="pricing")]

    def test_the_card_comes_first_with_its_status_priority_and_jira_key(self):
        out = self.ask("rollout")
        self.assertTrue(out.startswith("Rollout tracking"))
        for part in ("build", "P2", "CUD-1", "2026-11-12"):
            self.assertIn(part, out.splitlines()[0])

    def test_the_lead_is_the_first_sentence_or_two_of_the_one_paragraph_and_not_all_of_it(self):
        out = self.ask("rollout")
        self.assertIn("Rollout tracking is how the team follows the install", out)
        self.assertNotIn("A second sentence that goes on", out)

    def test_the_outcome_and_the_next_decision_are_shown_when_the_card_has_them(self):
        out = self.ask("rollout")
        self.assertIn("Outcome: Every distributor installed by March", out)
        self.assertIn("Next decision: Whether to pause the install in week 50", out)

    def test_open_questions_are_the_open_ones_for_this_card_most_urgent_first(self):
        out = self.ask("rollout")
        self.assertIn("Open (3)", out)
        self.assertLess(out.index(GAP(4)), out.index(GAP(2)))
        self.assertLess(out.index(GAP(2)), out.index(GAP(1)))
        self.assertNotIn(GAP(3), out, "a closed question is not listed")
        self.assertNotIn(GAP(5), out, "a question for another card is not listed")

    def test_people_and_systems_are_separate_lines_most_involved_first(self):
        out = self.ask("rollout")
        self.assertIn("People: Alex Roe (9), Sam Lee (6)", out)
        self.assertIn("Systems: Tag Tool", out)
        self.assertNotIn("Other Person", out)

    def test_the_newest_sources_are_listed_with_a_one_line_summary_and_the_count(self):
        out = self.ask("rollout")
        self.assertIn("Sources (4)", out)
        self.assertLess(out.index(DOC(9)), out.index(DOC(8)))
        self.assertIn("Digest 9 says something short.", out)

    def test_the_last_line_points_to_the_card_the_digests_and_their_sections(self):
        out = self.ask("rollout")
        last = out.strip().splitlines()[-1]
        self.assertIn("knowledge/features/rollout.md", last)
        self.assertIn("peek.py", last)
        self.assertIn("--section", last)

    def test_the_answer_stays_within_its_budget_and_keeps_the_pointers(self):
        out = self.ask("rollout", max_chars=700)
        self.assertLessEqual(len(out), 700)
        self.assertIn("peek.py", out.strip().splitlines()[-1])

    def test_a_card_with_no_open_questions_says_so(self):
        write(self.map / "open-items.json", json.dumps([]))
        self.assertIn("Open: none", self.ask("rollout"))


class FindingTheSubject(Case):
    ENTITIES = [person("Sam Lee", 6), person("Sam Wood", 2), {"id": "Tag Tool", "name": "Tag Tool", "type": "system", "aliases": ["TT"], "docs": [DOC(5), DOC(7)],
                "features": [{"slug": "rollout", "title": "Rollout tracking", "docs": 4, "kind": "feature"}], "neighbours": [],
                "relations": [{"rel": "is installed by", "to": "Sam Lee", "source": DOC(7), "dir": "out"}]}]

    def test_a_card_is_found_by_its_slug_its_title_or_the_start_of_either(self):
        for q in ("rollout", "Rollout Tracking", "rollout tr", "ROLLOUT"):
            self.assertTrue(self.ask(q).startswith("Rollout tracking"), q)

    def test_a_topic_card_is_found_too(self):
        self.assertTrue(self.ask("pricing").startswith("Pricing and promotions"))

    def test_a_person_or_system_is_found_by_name_or_alias_and_shows_where_it_appears(self):
        out = self.ask("TT")
        self.assertTrue(out.startswith("Tag Tool"))
        self.assertIn("system", out.splitlines()[0])
        self.assertIn("Rollout tracking", out)
        self.assertIn("is installed by Sam Lee", out)
        self.assertIn(DOC(7), out)

    def test_a_name_that_matches_two_things_lists_them_instead_of_guessing(self):
        with self.assertRaises(LookupError) as e:
            self.ask("Sam")
        self.assertIn("Sam Lee", str(e.exception))
        self.assertIn("Sam Wood", str(e.exception))

    def test_an_exact_name_wins_over_a_longer_one_that_contains_it(self):
        self.assertTrue(self.ask("Sam Lee").startswith("Sam Lee"))

    def test_a_card_wins_over_a_name_that_matches_at_the_same_step_and_the_name_is_offered(self):
        self.ENTITIES.append({"id": "rollout", "name": "rollout", "type": "system", "aliases": [], "docs": [DOC(5)], "features": [], "neighbours": [], "relations": []})
        write(self.map / "entities.json", json.dumps({"entities": self.ENTITIES, "candidates": [], "problems": []}))
        try:
            out = self.ask("rollout")
        finally:
            self.ENTITIES.pop()
        self.assertTrue(out.startswith("Rollout tracking"))
        self.assertIn("--entity", out.strip().splitlines()[-1])

    def test_entity_only_asks_for_the_name_not_the_card(self):
        self.ENTITIES.append({"id": "rollout", "name": "rollout", "type": "system", "aliases": [], "docs": [DOC(5)], "features": [], "neighbours": [], "relations": []})
        write(self.map / "entities.json", json.dumps({"entities": self.ENTITIES, "candidates": [], "problems": []}))
        try:
            out = self.ask("rollout", entity=True)
        finally:
            self.ENTITIES.pop()
        self.assertTrue(out.startswith("rollout (system"))

    def test_an_unknown_subject_says_so_and_offers_the_closest_names(self):
        with self.assertRaises(LookupError) as e:
            self.ask("rollut")
        self.assertIn("no card or name matches", str(e.exception))
        self.assertIn("rollout", str(e.exception))


class FilesListing(Case):
    def test_the_files_of_a_subject_are_listed_with_their_sizes_biggest_digests_first(self):
        write(self.map / "topic-files.json", json.dumps({"rollout": {"title": "Rollout tracking", "kind": "feature", "card": "knowledge/features/rollout.md", "card_bytes": 18757, "curated_bytes": 5200,
                 "digests": [{"id": DOC(5), "bytes": 3000}, {"id": DOC(7), "bytes": 9000}], "digest_bytes": 12000, "outputs": [{"file": "outputs/epics/rollout.md", "bytes": 700}], "open": 4}}))
        out = context.files_listing("rollout")
        self.assertIn("knowledge/features/rollout.md 18.8 KB (read the curated part first: 5.2 KB)", out)
        self.assertLess(out.index(DOC(7)), out.index(DOC(5)))
        self.assertIn("12.0 KB in all", out)
        self.assertIn("outputs/epics/rollout.md 700 B", out)
        self.assertIn("Open questions: 4", out)

    def test_a_subject_not_in_the_map_yet_says_to_rebuild(self):
        with self.assertRaises(LookupError) as e:
            context.files_listing("rollout")
        self.assertIn("build_map.py", str(e.exception))


if __name__ == "__main__":
    unittest.main()
