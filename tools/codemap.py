"""Write docs/system/CODEMAP.md: every tool and front-end file with its one-line purpose, size and neighbours (stdlib only).

    python tools/codemap.py          rewrite the map (build_map.py does this on every build)
    python tools/codemap.py --check  exit 1 if a file has no docstring or is over the size budget

Read the map first to find the module for a task instead of opening files. Generated; never edit by hand.
Budget: a Python file or script over BUDGET lines is listed under "Over budget" so it gets split (MANTIS-IMP-106).
"""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools"
OUT = ROOT / "docs" / "system" / "CODEMAP.md"
BUDGET = 600   # lines; the long-term target is 300, tightened as files are split


def _py():
    mods = {p.stem: p for p in sorted(TOOLS.glob("*.py"))}
    for pkg in ("pagebuild", "webserver"):   # the page builders and the site server
        mods.update({pkg + "/" + p.stem: p for p in sorted((TOOLS / pkg).glob("*.py")) if p.stem != "__init__"})
    info = {}
    for name, p in mods.items():
        text = p.read_text(encoding="utf-8")
        tree = ast.parse(text)
        doc = (ast.get_docstring(tree) or "").strip().splitlines()
        uses = set()
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                uses |= {a.name.split(".")[0] for a in n.names}
            elif isinstance(n, ast.ImportFrom) and n.module:
                uses.add(n.module.replace(".", "/") if n.module.startswith(("pagebuild.", "webserver.")) else n.module.split(".")[0])
        info[name] = {"doc": doc[0] if doc else "", "lines": text.count("\n") + 1, "uses": sorted(u for u in uses if u in mods and u != name)}
    for name, i in info.items():
        i["used_by"] = sorted(o for o, j in info.items() if name in j["uses"])
    return info


def _front():
    rows = []
    base = TOOLS / "site_assets"
    for p in sorted(base.rglob("*")):
        if not p.is_file() or p.suffix not in (".js", ".css") or "vendor" in p.parts:
            continue
        text = p.read_text(encoding="utf-8")
        m = re.match(r"\s*/\*+\s*(.*?)(?:\*/|\n\s*\n)", text, re.S)
        first = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
        if not first and text.lstrip().startswith("//"):   # a header made of // lines
            first = " ".join(re.findall(r"(?m)^//\s?(.*)$", text.lstrip().split("\n\n")[0])).strip()
        rows.append((p.relative_to(base).as_posix(), text.count("\n") + 1, first[:140]))
    return rows


def build():
    info, front = _py(), _front()
    out = ["# Code map", "", "Generated by `python tools/codemap.py` on every build. Find the module for a task here instead of opening files.",
           "Columns: lines, what it does, what it uses.", "", "## Python (tools/)", "", "file | lines | purpose | uses", "---|---|---|---"]
    for name, i in info.items():
        out.append(f"{name}.py | {i['lines']} | {i['doc'][:150].replace('|', '/') or '(no docstring)'} | {', '.join(i['uses'][:8])}")
    out += ["", "## Front end (tools/site_assets/)", "", "file | lines | purpose", "---|---|---"]
    out += [f"{f} | {n} | {d.replace('|', '/') or '(no header comment)'}" for f, n, d in front]
    big = [f"{n}.py ({i['lines']})" for n, i in info.items() if i["lines"] > BUDGET] + [f"{f} ({n})" for f, n, _ in front if n > BUDGET]
    out += ["", f"## Over budget ({BUDGET} lines)", "", ", ".join(big) or "none"]
    return "\n".join(out) + "\n", info, front, big


def main():
    text, info, front, big = build()
    if "--check" in sys.argv:
        bad = [f"{n}.py has no docstring" for n, i in info.items() if not i["doc"]] + [f"{f} has no header comment" for f, _, d in front if not d]
        print("\n".join(bad) or "ok")
        sys.exit(1 if bad else 0)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_bytes(text.encode("utf-8"))
        print(f"Code map: {len(info)} Python files, {len(front)} front-end files -> {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
