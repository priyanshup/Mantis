"""Does the incremental build know every file it reads? (IMP-111 step 7)

    python tools/inputscheck.py        run a full build with every file open recorded; list files under the repository that it read and that neither
                                       the build fingerprint (sitecache.inputs) nor the allowed list below covers. Exit 1 when there are any.

The site is only rebuilt when a fingerprinted file changes, so a file the build reads but the fingerprint misses would leave stale pages. The allowed list holds what the
build reads on purpose without needing it: the assets (always rebuilt), the web server, the pull, tests, generated files and the archive. A new read outside both is a finding:
add the folder to sitecache.inputs() when pages depend on it, or to ALLOWED here with the reason.
"""
import sys; sys.dont_write_bytecode = True  # keep __pycache__ out of OneDrive
import noconsole; noconsole.install()   # no console windows from background work (tools/noconsole.py)
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOWED = {
    "tools/site_assets/": "scripts, styles and fonts: always rebuilt, never skipped",
    "tools/webserver/": "the local server, not the pages",
    "tools/pullkit/": "the pull, not the pages",
    "tools/tests/": "tests",
    "tools/uitest/": "browser checks",
    "mantis/03_archive/": "read by the health report only",
    ".claude/skills/": "read by the skill check only",
    "tools/classify_config.json": "the classifier's cut-offs, read by the health report",
    "docs/system/CODEMAP.md": "generated by the build itself",
    "mantis/knowledge/map/": "generated by the build itself",
    "mantis/knowledge/assets/decisions.json": "written by the build's own asset step",
}


def undeclared(opened, covered, root=ROOT, allowed=None):
    """Files (repository-relative, sorted) read by the build that are neither fingerprinted nor allowed. __pycache__ and anything outside the repository are ignored."""
    allowed = ALLOWED if allowed is None else allowed
    root = Path(root).resolve()
    cov = {Path(p).resolve() for p in covered}
    out = set()
    for p in opened:
        p = Path(p).resolve()
        try:
            rel = p.relative_to(root).as_posix()
        except ValueError:
            continue
        if "__pycache__" in rel or ".git/" in rel or p in cov or any(rel.startswith(a) for a in allowed):
            continue
        out.add(rel)
    return sorted(out)


def trace_build():
    """Run build_map.py in this process with a full rebuild; returns the set of files it opened for reading."""
    import runpy
    opened = set()

    def hook(event, args):
        if event == "open" and isinstance(args[0], (str, bytes, os.PathLike)):
            mode = str(args[1]) if len(args) > 1 and args[1] is not None else "r"
            if not any(c in mode for c in "wax+"):
                try:
                    opened.add(os.path.abspath(os.fsdecode(args[0])))
                except (OSError, ValueError):
                    pass

    os.environ["MANTIS_FULL"] = "1"
    sys.path.insert(0, str(ROOT / "tools"))
    sys.argv = ["build_map.py", "--full"]
    sys.addaudithook(hook)
    try:
        runpy.run_path(str(ROOT / "tools" / "build_map.py"), run_name="__main__")
    except SystemExit:
        pass
    return opened


def main():
    opened = trace_build()
    import sitecache
    bad = undeclared(opened, [p for p, _, _ in sitecache.inputs()])
    for rel in bad:
        print(f"read but not fingerprinted: {rel}")
    print(f"{len(opened)} files read, {len(bad)} outside the fingerprint and the allowed list")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
